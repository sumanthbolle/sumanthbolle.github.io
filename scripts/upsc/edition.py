def _pyq_options(candidate: Mapping[str, Any], bank: Any, limit: int = 3) -> list[dict[str, Any]]:
    rows = bank.get("questions") if isinstance(bank, dict) else bank
    words = tokens(candidate.get("title", "") + " " + " ".join(
        str(row.get("officialSummary") or "") for row in candidate.get("records") or []
    ))
    scored = []
    for row in rows if isinstance(rows, list) else []:
        if not isinstance(row, dict) or not row.get("id"):
            continue
        overlap = len(words & tokens(" ".join(row.get("tags") or []) + " " + str(row.get("question") or "")))
        if overlap >= 2:
            scored.append((-overlap, str(row["id"]), row))
    return [row for _, _, row in sorted(scored, key=lambda item: item[:2])[:limit]]


def _source(record: Mapping[str, Any]) -> dict[str, str]:
    return {
        "title": str(record.get("title") or ""),
        "url": str(record.get("sourceUrl") or ""),
        "publisher": str(record.get("publisherName") or record.get("publisherId") or ""),
    }


def _registry_hosts(output_root: Path) -> set[str]:
    rows = _read_json(output_root / "source-registry.json", [])
    hosts: set[str] = set()
    for row in rows if isinstance(rows, list) else []:
        if isinstance(row, dict) and row.get("enabled", True):
            hosts.update(str(host) for host in row.get("hosts") or [])
    return hosts


def _fetch(record: Mapping[str, Any], opener: Callable[..., Any], failures: dict[str, int]) -> dict[str, Any]:
    result = fetch_evidence(dict(record), opener, fallback=curl_open if opener is urlopen else None)
    if not result["ok"]:
        failures[result["reason"]] = failures.get(result["reason"], 0) + 1
    return result


def _official_evidence(
    candidate: Mapping[str, Any], opener: Callable[..., Any], failures: dict[str, int],
) -> tuple[list[dict[str, Any]], str]:
    evidence: list[dict[str, Any]] = []
    reason = ""
    for row in candidate["records"][:MAX_EVIDENCE_RECORDS]:
        result = _fetch(row, opener, failures)
        if not result["ok"]:
            reason = reason or result["reason"]
            continue
        evidence.append({
            "title": str(row.get("title") or ""), "publisher": _source(row)["publisher"],
            "url": str(row.get("sourceUrl") or ""), "date": str(row.get("publishedAt") or "")[:10],
            "kind": "official", "text": result["text"],
        })
    return evidence, reason


def _newspaper_evidence(
    candidate: Mapping[str, Any], opener: Callable[..., Any], failures: dict[str, int], registry_hosts: set[str],
) -> tuple[list[dict[str, Any]], list[dict[str, Any]], str]:
    """Fetch up to two newspaper articles (distinct publishers), then any official
    pages they link to. Returns (official, discovery, first failure reason)."""
    articles, publishers = [], set()
    for item in candidate.get("discovery") or []:
        if item.get("publisher") not in publishers:
            publishers.add(item.get("publisher"))
            articles.append(item)
    official: list[dict[str, Any]] = []
    discovery: list[dict[str, Any]] = []
    tried: set[str] = set()
    reason = ""
    for item in articles[:2]:
        result = _fetch({"sourceUrl": item.get("url")}, opener, failures)
        if not result["ok"]:
            reason = reason or result["reason"]
            continue
        discovery.append({
            "title": str(item.get("title") or ""), "publisher": str(item.get("publisher") or ""),
            "url": str(item.get("url") or ""), "date": str(item.get("publishedAt") or "")[:10],
            "kind": "discovery", "text": result["text"],
        })
        for link in official_links(result["links"], registry_hosts):
            if link in tried or len(official) >= 2:
                continue
            tried.add(link)
            page = _fetch({"sourceUrl": link}, opener, failures)
            if page["ok"]:
                official.append({
                    "title": page["title"] or str(item.get("title") or ""),
                    "publisher": urlsplit(page["url"]).hostname or "", "url": link,
                    "date": str(item.get("publishedAt") or "")[:10], "kind": "official", "text": page["text"],
                })
    return official, discovery, reason


def _gather_evidence(
    candidate: Mapping[str, Any],
    opener: Callable[..., Any],
    failures: dict[str, int],
    registry_hosts: Optional[set[str]] = None,
) -> tuple[list[dict[str, Any]], str, str]:
    """Return (numbered evidence, first failure reason, note kind).

    Official records are fetched directly. A newspaper-only topic first looks
    for official pages linked from the article: if one is reachable the note is
    ordinary news citing official and newspaper sources; otherwise it is a
    secondary (or editorial) note citing the newspaper.
    """
    kind = str(candidate.get("kind") or "news")
    if candidate.get("records"):
        evidence, reason = _official_evidence(candidate, opener, failures)
    else:
        official, discovery, reason = _newspaper_evidence(candidate, opener, failures, registry_hosts or set())
        evidence = official + discovery
        if official:
            kind = "news"
    for index, row in enumerate(evidence, start=1):
        row["n"] = index
    return evidence, reason, kind


def _note_id(edition: str, fingerprint: str) -> str:
    return f"{edition}-{fingerprint[:10]}"


def _complete_note(
    note: dict[str, Any], candidate: Mapping[str, Any], edition: str, date: str, now: str,
) -> dict[str, Any]:
    fingerprint = str(candidate["fingerprint"])
    note.update({
        "id": _note_id(edition, fingerprint),
        "slug": f"{date}-{_slug(candidate['title'], 'note')[:70].rstrip('-')}-{fingerprint[:6]}",
        "fingerprint": fingerprint,
        "topicTitle": candidate["title"],
        "recordIds": [row["id"] for row in candidate.get("records") or []],
        "publishedAt": now,
        "priority": int(candidate.get("score") or 0),
        "band": candidate.get("band", "must"),
        "updates": [],
    })
    if candidate.get("anchorHint") and not note.get("anchor"):
        note["anchor"] = candidate["anchorHint"]
    return note


def _is_mains(note: Mapping[str, Any], candidate: Mapping[str, Any]) -> bool:
    parts = candidate.get("scoreParts") or {}
    return (
        note.get("kind") != "news"
        or int(parts.get("anchor") or 0) > 0
        or bool((note.get("practice") or {}).get("pyq"))
    )


def _matches(candidate: Mapping[str, Any], note: Mapping[str, Any]) -> bool:
    if candidate.get("fingerprint") == note.get("fingerprint"):
        return True
    record_ids = {row.get("id") for row in candidate.get("records") or []}
    if record_ids & set(note.get("recordIds") or []):
        return True
    return similar(tokens(candidate.get("title", "")), tokens(str(note.get("topicTitle") or "")))


def _quick_fact(candidate: Mapping[str, Any]) -> Optional[dict[str, Any]]:
    records = candidate.get("records") or []
    codes = candidate.get("codesHint") or []
    if not codes:
        return None
    if records:
        lead = records[0]
        return {
            "id": f"qf-{lead['id']}", "fact": str(lead.get("title") or ""),
            "code": codes[0], "source": {**_source(lead), "kind": "official"},
        }
    item = (candidate.get("discovery") or [None])[0]
    if not item:
        return None
    return {
        "id": "qf-d-" + sha1(str(item.get("url") or "").encode("utf-8")).hexdigest()[:12],
        "fact": str(item.get("title") or ""), "code": codes[0],
        "source": {"title": str(item.get("title") or ""), "url": str(item.get("url") or ""),
                   "publisher": str(item.get("publisher") or ""), "kind": "discovery"},
    }


def _brief(row: Mapping[str, Any]) -> dict[str, Any]:
    return {
        "title": row["title"], "score": row["score"], "band": row.get("band"), "kind": row.get("kind"),
        "codes": row.get("codesHint"), "parts": row.get("scoreParts"),
        "publishers": sorted({str(item.get("publisher") or "") for item in row.get("discovery") or []}),
        "records": len(row.get("records") or []),
    }


def _empty_edition(date: str, slot: str, window: tuple[str, str]) -> dict[str, Any]:
    return {
        "id": edition_id(date, slot), "slot": slot, "date": date,
        "window": {"from": window[0], "to": window[1]},
        "closedAt": "", "status": "partial", "glimpse": [], "prelims": [], "mains": [],
        "quickFacts": [], "held": [], "notes": {},
    }


def _counts(edition: Mapping[str, Any]) -> dict[str, int]:
    return {
        "notes": len(edition.get("notes") or {}), "prelims": len(edition.get("prelims") or []),
        "mains": len(edition.get("mains") or []), "quickFacts": len(edition.get("quickFacts") or []),
        "held": len(edition.get("held") or []),
    }


def _build_index(output_root: Path, now: str) -> dict[str, Any]:
    rows = []
    for path in sorted((output_root / "editions").glob("*/*/*.json")):
        payload = _read_json(path, None)
        if not isinstance(payload, dict) or not payload.get("id"):
            continue
        rows.append({
            "id": payload["id"], "date": payload.get("date"), "slot": payload.get("slot"),
            "status": payload.get("status"), "closedAt": payload.get("closedAt"),
            "path": path.relative_to(output_root).as_posix(),
            "counts": _counts(payload),
        })
    rows.sort(key=lambda row: row["id"], reverse=True)
    return {"generatedAt": now, "editions": rows[:INDEX_LIMIT]}


def _same(left: Any, right: Any, ignore: tuple[str, ...] = ("closedAt", "generatedAt")) -> bool:
    if not isinstance(left, dict) or not isinstance(right, dict):
        return False
    strip = lambda row: {key: value for key, value in row.items() if key not in ignore}
    return strip(left) == strip(right)


def _ensure_site(site_root: Path) -> None:
    if not site_root.exists() or not any(site_root.iterdir()):
        site_root.mkdir(parents=True, exist_ok=True)
        (site_root / ".upsc-generated").write_text(GENERATED_MARKER, encoding="utf-8")


def build_edition(
    output_root: Path,
    date: str,
    slot: str,
    now: str,
    opener: Callable[..., Any],
    transport: Callable[..., Any],
    dry_run: bool = False,
    max_notes: int = 8,
    env: Optional[Mapping[str, str]] = None,
    site_root: Optional[Path] = None,
    feeds_path: Optional[Path] = None,
    base_url: str = BASE_URL,
) -> dict[str, Any]:
    output_root = Path(output_root)
    site_root = Path(site_root) if site_root else ROOT / "upsc-study"
    env = os.environ if env is None else env
    window = slot_window(date, slot)
    this_id = edition_id(date, slot)
    path = _edition_path(output_root, date, slot)
    existing = _read_json(path, None)
    edition = json.loads(json.dumps(existing)) if isinstance(existing, dict) else _empty_edition(date, slot, window)
    edition["window"] = {"from": window[0], "to": window[1]}

    feed_errors: list[dict[str, str]] = []
    # 24 hours before the window as well: earlier coverage of a story still
    # counts, but only topics with an item inside the window become candidates.
    lookback = _iso(_parse(window[0]) - timedelta(hours=24))
    fetched = fetch_discovery(
        load_feeds(feeds_path or ROOT / "data/upsc/discovery-feeds.json"), opener,
        lookback, window[1], feed_errors,
    )
    archived = load_archived(output_root, lookback, window[1])
    seen_urls = {row["url"] for row in fetched}
    discovery = fetched + [row for row in archived if row["url"] not in seen_urls]
    records, _ = _all_current_records(output_root)
    candidates = build_candidates(records.values(), discovery, window)

    # The previous edition (same-day AM for PM, previous day's PM for AM) owns
    # topics it already covered: new official records become updates there.
    am_date, am_slot = _previous_slot(date, slot)
    am_path = _edition_path(output_root, am_date, am_slot)
    am = _read_json(am_path, None)
    am_changed = False
    pyq_bank = _read_json(PYQ_BANK_PATH, {})
    registry_hosts = _registry_hosts(output_root)
    evidence_failures: dict[str, int] = {}
    held: list[dict[str, Any]] = []
    new_notes: list[tuple[dict[str, Any], dict[str, Any]]] = []
    quick_facts = list(edition.get("quickFacts") or [])
    fact_ids = {row.get("id") for row in quick_facts}
    llm_down = False

    pool: list[dict[str, Any]] = []
    produced = len(edition.get("notes") or {})
    for candidate in candidates:
        candidate["band"] = "skip"
        if any(_matches(candidate, note) for note in (edition.get("notes") or {}).values()):
            candidate["band"] = "must"
            continue
        if isinstance(am, dict):
            am_note = next((note for note in (am.get("notes") or {}).values() if _matches(candidate, note)), None)
            if am_note is not None:
                fresh = [row for row in candidate["records"] if row["id"] not in set(am_note.get("recordIds") or [])]
                for row in fresh:
                    am_note.setdefault("updates", []).append({"at": now, "text": str(row.get("title") or ""), "source": _source(row)})
                    am_note.setdefault("recordIds", []).append(row["id"])
                    am_changed = True
                candidate["band"] = "update"
                continue
        if int(candidate["score"]) >= FACT_FLOOR:
            pool.append(candidate)

    attempted: set[str] = set()
    fact_first: list[dict[str, Any]] = []
    attempts_left = max_notes + EXTRA_ATTEMPTS
    for candidate in note_queue(pool):
        if produced >= max_notes or attempts_left <= 0:
            break
        attempts_left -= 1
        attempted.add(candidate["fingerprint"])
        candidate["band"] = "must"
        topic = {"topic": candidate["title"], "fingerprint": candidate["fingerprint"]}
        try:
            evidence, reason, kind = _gather_evidence(candidate, opener, evidence_failures, registry_hosts)
            if not evidence:
                # Not counted against the slot: the next candidate takes its place,
                # and the topic still reaches readers as a quick fact.
                held.append({**topic, "reasons": ["evidence-unavailable", reason or "no-evidence"]})
                fact_first.append(candidate)
                continue
            produced += 1
            if llm_down:
                held.append({**topic, "reasons": ["llm-unavailable"]})
                continue
            note, reasons = write_note(dict(candidate, kind=kind), evidence, _pyq_options(candidate, pyq_bank), transport, env=env)
        except Exception as error:  # one topic never sinks the edition
            held.append({**topic, "reasons": ["error", str(error)[:200]]})
            continue
        if note is None:
            llm_down = llm_down or reasons == ["llm-unavailable"]
            held.append({**topic, "reasons": reasons})
            continue
        new_notes.append((_complete_note(note, candidate, this_id, date, now), candidate))

    remaining = sorted(
        fact_first + [row for row in pool if row["fingerprint"] not in attempted],
        key=lambda row: (-int(row["score"]), row["title"], row["fingerprint"]),
    )
    for candidate in remaining:
        if len(quick_facts) >= MAX_FACTS:
            break
        fact = _quick_fact(candidate)
        if fact and fact["id"] not in fact_ids:
            fact_ids.add(fact["id"])
            quick_facts.append(fact)
            if candidate["band"] == "skip":
                candidate["band"] = "useful"

    notes = dict(edition.get("notes") or {})
    for note, candidate in new_notes:
        notes[note["id"]] = note
        edition["mains" if _is_mains(note, candidate) else "prelims"].append(note["id"])
        edition["glimpse"].append({"noteId": note["id"], "line": note.get("oneLine", ""), "code": (note.get("codes") or [""])[0]})
    edition["notes"] = notes
    edition["quickFacts"] = quick_facts
    edition["held"] = held
    llm_held = any("llm-unavailable" in row["reasons"] for row in held)
    edition["status"] = "partial" if llm_held or (not notes and held) else "closed"
    edition["closedAt"] = now

    must = [row for row in candidates if row["band"] == "must"]
    facts = [row for row in candidates if row["band"] == "useful"]
    report: dict[str, Any] = {
        "editionId": this_id, "dryRun": dry_run, "window": edition["window"],
        "discovery": {
            "items": len(discovery), "fetched": len(fetched),
            "inWindow": sum(1 for row in discovery if window[0] <= row["publishedAt"] < window[1]),
            "fromArchive": len(discovery) - len(fetched), "feedErrors": feed_errors,
        },
        "candidates": {band: sum(1 for row in candidates if row["band"] == band) for band in ("must", "useful", "update", "skip")},
        "mustKnow": [_brief(row) for row in must],
        "quickFactTopics": [_brief(row) for row in facts],
        "ranked": [_brief(row) for row in candidates],
        "evidenceFailures": evidence_failures,
        "newNotes": len(new_notes), "held": held, "status": edition["status"],
        "written": [], "edition": edition,
    }
    if dry_run:
        return report

    for archive_path in archive_items(output_root, fetched):
        report["written"].append(archive_path.as_posix())
    if not _same(existing, edition):
        _write_json(path, edition)
        report["written"].append(path.as_posix())
    if am_changed:
        _write_json(am_path, am)
        report["written"].append(am_path.as_posix())
    pages = [(note, this_id) for note, _ in new_notes]
    if am_changed:
        pages += [(note, am["id"]) for note in am["notes"].values() if note.get("updates")]
    if pages:
        _ensure_site(site_root)
    for note, owner in pages:
        page = site_root / "notes" / _slug(note["slug"], "note") / "index.html"
        _write_text(page, render_note_page(note, owner, base_url))
        report["written"].append(page.as_posix())
    index_path = output_root / "editions" / "index.json"
    index = _build_index(output_root, now)
    if not _same(_read_json(index_path, None), index):
        _write_json(index_path, index)
        report["written"].append(index_path.as_posix())
    return report


def _summary(report: Mapping[str, Any]) -> dict[str, Any]:
    held_reasons: dict[str, int] = {}
    for row in report["held"]:
        key = row["reasons"][0] if row["reasons"] else "unknown"
        held_reasons[key] = held_reasons.get(key, 0) + 1
    edition = report["edition"]
    return {
        "editionId": report["editionId"], "dryRun": report["dryRun"], "status": report["status"],
        "window": report["window"], "discovery": report["discovery"],
        "candidates": report["candidates"], "notesSelected": report["mustKnow"],
        "quickFactTopics": report["quickFactTopics"], "ranked": report["ranked"][:40],
        "evidenceFailures": report["evidenceFailures"], "heldByReason": held_reasons,
        "held": report["held"], "newNotes": report["newNotes"],
        "counts": _counts(edition), "written": report["written"],
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--slot", choices=("am", "pm", "auto"), default="auto")
    parser.add_argument("--date", help="IST date YYYY-MM-DD (default: today in IST)")
    parser.add_argument("--dry-run", action="store_true")
    parser.add_argument("--max-notes", type=int, default=8)
    parser.add_argument("--output", type=Path, default=ROOT / "data/upsc")
    parser.add_argument("--site-root", type=Path, default=ROOT / "upsc-study")
    parser.add_argument("--feeds", type=Path, default=ROOT / "data/upsc/discovery-feeds.json")
    parser.add_argument("--now")
    args = parser.parse_args()
    now = args.now or _iso(datetime.now(timezone.utc))
    slot, today = resolve_slot(args.slot, now)
    report = build_edition(
        args.output, args.date or today, slot, now, urlopen, urlopen,
        dry_run=args.dry_run, max_notes=args.max_notes, site_root=args.site_root,
        feeds_path=args.feeds,
    )
    print(json.dumps(_summary(report), indent=2, ensure_ascii=False))
    return 0


