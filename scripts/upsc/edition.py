#!/usr/bin/env python3
"""Build the AM or PM UPSC edition: discover, bind, rank, write, gate, emit.

An edition file is written atomically and only when its content changes, so
a retry run adds missing topics without disturbing note ids that browsers
already hold done-state for. LLM or evidence failures hold single notes; the
run itself always finishes and reports.
"""

