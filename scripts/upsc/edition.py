ROOT = Path(__file__).resolve().parents[2]
IST = timezone(timedelta(hours=5, minutes=30))
SLOTS = ("am", "pm")
BASE_URL = "https://sumanthbolle.com"
INDEX_LIMIT = 60
MAX_EVIDENCE_RECORDS = 3
GENERATED_MARKER = "Generated by scripts/upsc/publish.py build-pages. Do not edit.\n"


def _iso(moment: datetime) -> str:
    return moment.astimezone(timezone.utc).replace(microsecond=0).isoformat().replace("+00:00", "Z")


def _parse(value: str) -> datetime:
    return datetime.fromisoformat(str(value).replace("Z", "+00:00"))


def slot_window(date_ist: str, slot: str) -> tuple[str, str]:
    """AM: 18:00 IST previous day to 06:00 IST. PM: 06:00 to 18:00 IST."""
    if slot not in SLOTS:
        raise ValueError("slot must be am or pm")
    day = date_type.fromisoformat(date_ist)
    six_am = datetime(day.year, day.month, day.day, 6, tzinfo=IST)
    if slot == "am":
        return _iso(six_am - timedelta(hours=12)), _iso(six_am)
    return _iso(six_am), _iso(six_am + timedelta(hours=12))


def edition_id(date: str, slot: str) -> str:
    return f"{date}-{slot}"


def resolve_slot(slot: str, now: str) -> tuple[str, str]:
    """Return (slot, IST date). `auto` is AM before noon IST, otherwise PM."""
    local = _parse(now).astimezone(IST)
    if slot == "auto":
        slot = "am" if local.hour < 12 else "pm"
    return slot, local.date().isoformat()


def _edition_path(output_root: Path, date: str, slot: str) -> Path:
    year, month, day = date.split("-")
    return output_root / "editions" / year / month / f"{day}-{slot}.json"


# --- static note page -------------------------------------------------------

def _safe_url(value: Any) -> str:
    url = str(value or "").strip()
    parts = urlsplit(url)
    return url if parts.scheme in ("http", "https") and parts.hostname else ""


def _text(value: Any) -> str:
    return escape(str(value or ""))


def _chips(refs: Any, sources: dict[int, dict[str, Any]]) -> str:
    chips = []
    for ref in refs if isinstance(refs, list) else [refs]:
        source = sources.get(ref) if isinstance(ref, int) else None
        if not source:
            continue
        label = f"[{ref}] {source.get('publisher') or 'Source'}"
        url = _safe_url(source.get("url"))
        kind = "official" if source.get("kind") == "official" else "secondary"
        chips.append(
            f'<a class="ue-chip ue-chip--{kind}" href="{escape(url, quote=True)}" rel="noopener noreferrer">{_text(label)}</a>'
            if url else f'<span class="ue-chip ue-chip--{kind}">{_text(label)}</span>'
        )
    return f'<p class="ue-sources">{"".join(chips)}</p>' if chips else ""


def _bullets(rows: Any) -> str:
    items = []
    for row in rows if isinstance(rows, list) else []:
        if not isinstance(row, dict) or not row.get("text"):
            continue
        label = str(row.get("label") or "").strip().rstrip(".")
        prefix = f"<strong>{_text(label)}.</strong> " if label else ""
        items.append(f"<li>{prefix}{_text(row.get('text'))}</li>")
    return f"<ul>{''.join(items)}</ul>" if items else ""


def _practice(practice: Mapping[str, Any]) -> str:
    parts = []
    mcq = practice.get("mcq") if isinstance(practice.get("mcq"), dict) else {}
    if mcq:
        options = "".join(f"<li>{_text(option)}</li>" for option in mcq.get("options") or [])
        answer = mcq.get("answer")
        letter = "abcd"[answer] if isinstance(answer, int) and 0 <= answer <= 3 else ""
        parts.append(
            f'<section class="ue-mcq"><h3>Prelims MCQ</h3><p>{_text(mcq.get("stem"))}</p>'
            f'<ol type="a">{options}</ol><details><summary>Answer and trap</summary>'
            f'<p>Answer: ({letter}). {_text(mcq.get("trap"))}</p></details></section>'
        )
    mains = practice.get("mains") if isinstance(practice.get("mains"), dict) else {}
    if mains:
        structure = mains.get("structure") if isinstance(mains.get("structure"), dict) else {}
        body = "".join(f"<li>{_text(point)}</li>" for point in structure.get("body") or [])
        parts.append(
            f'<section class="ue-mains"><h3>Mains question ({_text(mains.get("marks"))} marks)</h3>'
            f'<p>{_text(mains.get("question"))}</p><p><strong>{_text(mains.get("directive"))}:</strong> '
            f'{_text(mains.get("demand"))}</p><p>Intro: {_text(structure.get("intro"))}</p>'
            f'<ul>{body}</ul><p>Conclusion: {_text(structure.get("conclusion"))}</p></section>'
        )
    pyq = practice.get("pyq") if isinstance(practice.get("pyq"), dict) else {}
    if pyq:
        parts.append(
            f'<section class="ue-pyq"><h3>Previous year question ({_text(pyq.get("year"))}, {_text(pyq.get("paper"))})</h3>'
            f'<p>{_text(pyq.get("question"))}</p><p>{_text(pyq.get("why"))}</p></section>'
        )
    faq = "".join(
        f"<dt>{_text(row.get('q'))}</dt><dd>{_text(row.get('a'))}</dd>"
        for row in practice.get("faq") or [] if isinstance(row, dict)
    )
    if faq:
        parts.append(f'<section class="ue-faq"><h3>Quick revision</h3><dl>{faq}</dl></section>')
    return (
        '<details class="ue-practice"><summary>Practice: MCQ, Mains and revision</summary>'
        + "".join(parts) + "</details>"
    )


def render_note_page(note: Mapping[str, Any], edition: str, base_url: str = BASE_URL) -> str:
    sources = {row.get("n"): row for row in note.get("sources") or [] if isinstance(row, dict)}
    slug = _slug(note.get("slug"), "note")
    canonical = f"{base_url.rstrip('/')}/upsc-study/notes/{slug}/"
    title = str(note.get("title") or "UPSC study note")
    description = str(note.get("oneLine") or note.get("deck") or title)[:200]
    published = str(note.get("publishedAt") or "")
    codes = ", ".join(str(code) for code in note.get("codes") or [])
    why = note.get("whyInNews") if isinstance(note.get("whyInNews"), dict) else {}
    body = [
        f'<p class="ue-tagline">{_text(note.get("subject"))} · {_text(codes)} · {_text(published[:10])} · '
        f'{_text(note.get("readTime"))} · {_text(edition)}</p>',
        f"<h1>{_text(title)}</h1>",
        f'<p class="ue-deck">{_text(note.get("deck"))}</p>',
        f'<p class="ue-oneline">{_text(note.get("oneLine"))}</p>',
        f'<section class="ue-why"><h2>Why is this in the news?</h2><p>{_text(why.get("text"))}</p>'
        f'{_chips(why.get("sources"), sources)}</section>',
    ]
    for section in note.get("sections") or []:
        if isinstance(section, dict):
            body.append(
                f"<section><h2>{_text(section.get('heading'))}</h2>{_bullets(section.get('body'))}"
                f"{_chips(section.get('sources'), sources)}</section>"
            )
    numbers = "".join(
        f'<tr><td data-label="Figure">{_text(row.get("figure"))}</td>'
        f'<td data-label="What it measures">{_text(row.get("meaning"))}</td>'
        f'<td data-label="Source">{_chips(row.get("source"), sources)}</td></tr>'
        for row in note.get("keyNumbers") or [] if isinstance(row, dict)
    )
    if numbers:
        body.append(
            '<section class="ue-keynumbers"><h2>Key numbers</h2><div class="ue-table-wrap"><table>'
            "<thead><tr><th>Figure</th><th>What it measures</th><th>Source</th></tr></thead>"
            f'<tbody>{numbers}</tbody></table></div><span id="ue-keynumbers-end"></span></section>'
        )
    basics = note.get("back2basics") if isinstance(note.get("back2basics"), dict) else {}
    if basics:
        body.append(
            f'<section class="ue-basics"><h2>Back to basics: {_text(basics.get("concept"))}</h2>'
            f'<p>{_text(basics.get("text"))}</p></section>'
        )
    way = [row for row in note.get("wayForward") or [] if isinstance(row, dict)]
    if way:
        body.append(f'<section class="ue-way"><h2>What happens next?</h2>{_bullets(way)}</section>')
    if note.get("misconception"):
        body.append(f'<aside class="ue-misconception"><strong>Common mistake.</strong> {_text(note.get("misconception"))}</aside>')
    if isinstance(note.get("practice"), dict):
        body.append(_practice(note["practice"]))
    updates = "".join(
        f'<li><time>{_text(str(row.get("at") or "")[:16].replace("T", " "))}</time> {_text(row.get("text"))}'
        f'{" — " + _source_link(row.get("source")) if isinstance(row.get("source"), dict) else ""}</li>'
        for row in note.get("updates") or [] if isinstance(row, dict)
    )
    if updates:
        body.append(f'<section class="ue-updates"><h2>Updates</h2><ul>{updates}</ul></section>')
    trail = "".join(
        f'<li>[{_text(row.get("n"))}] {_source_link(row)} · {_text(row.get("date"))}'
        f'{" · newspaper" if row.get("kind") == "discovery" else " · official"}</li>'
        for row in note.get("sources") or [] if isinstance(row, dict)
    )
    body.append(f'<section class="ue-trail"><h2>Sources</h2><ol>{trail}</ol></section>')
    article = {
        "@context": "https://schema.org", "@type": "Article",
        "headline": title[:110], "description": description, "url": canonical,
        "mainEntityOfPage": canonical, "datePublished": published, "dateModified": published,
        "inLanguage": "en-IN", "about": codes,
        "isBasedOn": [url for url in (_safe_url(row.get("url")) for row in note.get("sources") or [] if isinstance(row, dict)) if url],
        "author": {"@type": "Person", "name": "Sumanth Bolle"},
        "publisher": {"@type": "Organization", "name": "Anchor UPSC"},
    }
    json_ld = json.dumps(article, ensure_ascii=False, separators=(",", ":")).replace("<", "\\u003c")
    return f'''<!doctype html>
<html lang="en"><head>
<meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>{_text(title)}</title>
<meta name="description" content="{escape(description, quote=True)}">
<link rel="canonical" href="{escape(canonical, quote=True)}">
<meta property="og:type" content="article"><meta property="og:title" content="{escape(title, quote=True)}">
<meta property="og:description" content="{escape(description, quote=True)}">
<meta property="og:url" content="{escape(canonical, quote=True)}">
<script type="application/ld+json">{json_ld}</script>
<link rel="stylesheet" href="/assets/css/upsc-edition.css">
</head><body class="ue-page"><header class="ue-header"><nav><a href="/upsc">Open study desk</a> <a href="/upsc-study/">Study archive</a></nav></header>
<main><article class="ue-note">{"".join(body)}</article></main>
<footer class="ue-footer">Written from official sources listed above. UPSC notifications and syllabus remain controlling.</footer>
</body></html>
'''


def _source_link(source: Any) -> str:
    if not isinstance(source, dict):
        return ""
    label = f"{source.get('publisher') or 'Source'}: {source.get('title') or ''}".strip(": ")
    url = _safe_url(source.get("url"))
    if not url:
        return _text(label)
    return f'<a href="{escape(url, quote=True)}" rel="noopener noreferrer">{_text(label)}</a>'


# --- edition assembly -------------------------------------------------------

def _pyq_options(candidate: Mapping[str, Any], bank: Any, limit: int = 3) -> list[dict[str, Any]]:
    rows = bank.get("questions") if isinstance(bank, dict) else bank
    words = tokens(candidate.get("title", "") + " " + " ".join(
        str(row.get("officialSummary") or "") for row in candidate.get("records") or []
    ))
    scored = []
    for row in rows if isinstance(rows, list) else []:
        if not isinstance(row, dict) or not row.get("id"):
            continue
        overlap = len(words & tokens(" ".join(row.get("tags") or []) + " " + str(row.get("question") or "")))
        if overlap >= 2:
            scored.append((-overlap, str(row["id"]), row))
    return [row for _, _, row in sorted(scored, key=lambda item: item[:2])[:limit]]


def _source(record: Mapping[str, Any]) -> dict[str, str]:
    return {
        "title": str(record.get("title") or ""),
        "url": str(record.get("sourceUrl") or ""),
        "publisher": str(record.get("publisherName") or record.get("publisherId") or ""),
    }


def _gather_evidence(
    candidate: Mapping[str, Any],
    opener: Callable[..., Any],
    failures: dict[str, int],
) -> tuple[list[dict[str, Any]], str]:
    fallback = curl_open if opener is urlopen else None
    evidence: list[dict[str, Any]] = []
    reason = ""
    if candidate.get("records"):
        items = [(row, "official", _source(row)["publisher"], row.get("sourceUrl"), str(row.get("publishedAt") or "")[:10])
                 for row in candidate["records"][:MAX_EVIDENCE_RECORDS]]
    else:
        items = [({"sourceUrl": row.get("url")}, "discovery", row.get("publisher"), row.get("url"), str(row.get("publishedAt") or "")[:10])
                 for row in candidate.get("discovery", [])[:1]]
    for index, (record, kind, publisher, url, day) in enumerate(items):
        result = fetch_evidence(dict(record), opener, fallback=fallback)
        if not result["ok"]:
            failures[result["reason"]] = failures.get(result["reason"], 0) + 1
            reason = reason or result["reason"]
            continue
        title = record.get("title") or (candidate.get("discovery") or [{}])[0].get("title", "")
        evidence.append({
            "n": len(evidence) + 1, "title": str(title or ""), "publisher": str(publisher or ""),
            "url": str(url or ""), "date": day, "kind": kind, "text": result["text"],
        })
    return evidence, reason


def _note_id(edition: str, fingerprint: str) -> str:
    return f"{edition}-{fingerprint[:10]}"


def _complete_note(
    note: dict[str, Any], candidate: Mapping[str, Any], edition: str, date: str, now: str,
) -> dict[str, Any]:
    fingerprint = str(candidate["fingerprint"])
    note.update({
        "id": _note_id(edition, fingerprint),
        "slug": f"{date}-{_slug(candidate['title'], 'note')[:70].rstrip('-')}-{fingerprint[:6]}",
        "fingerprint": fingerprint,
        "topicTitle": candidate["title"],
        "recordIds": [row["id"] for row in candidate.get("records") or []],
        "publishedAt": now,
        "priority": int(candidate.get("score") or 0),
        "band": candidate.get("band", "must"),
        "updates": [],
    })
    if candidate.get("anchorHint") and not note.get("anchor"):
        note["anchor"] = candidate["anchorHint"]
    return note


def _is_mains(note: Mapping[str, Any], candidate: Mapping[str, Any]) -> bool:
    parts = candidate.get("scoreParts") or {}
    return (
        note.get("kind") != "news"
        or int(parts.get("anchor") or 0) > 0
        or bool((note.get("practice") or {}).get("pyq"))
    )


def _matches(candidate: Mapping[str, Any], note: Mapping[str, Any]) -> bool:
    if candidate.get("fingerprint") == note.get("fingerprint"):
        return True
    record_ids = {row.get("id") for row in candidate.get("records") or []}
    if record_ids & set(note.get("recordIds") or []):
        return True
    return similar(tokens(candidate.get("title", "")), tokens(str(note.get("topicTitle") or "")))


def _quick_fact(candidate: Mapping[str, Any]) -> Optional[dict[str, Any]]:
    records = candidate.get("records") or []
    codes = candidate.get("codesHint") or []
    if not records or not codes:
        return None
    lead = records[0]
    return {
        "id": f"qf-{lead['id']}", "fact": str(lead.get("title") or ""),
        "code": codes[0], "source": _source(lead),
    }


def _empty_edition(date: str, slot: str, window: tuple[str, str]) -> dict[str, Any]:
    return {
        "id": edition_id(date, slot), "slot": slot, "date": date,
        "window": {"from": window[0], "to": window[1]},
        "closedAt": "", "status": "partial", "glimpse": [], "prelims": [], "mains": [],
        "quickFacts": [], "held": [], "notes": {},
    }


def _counts(edition: Mapping[str, Any]) -> dict[str, int]:
    return {
        "notes": len(edition.get("notes") or {}), "prelims": len(edition.get("prelims") or []),
        "mains": len(edition.get("mains") or []), "quickFacts": len(edition.get("quickFacts") or []),
        "held": len(edition.get("held") or []),
    }


def _build_index(output_root: Path, now: str) -> dict[str, Any]:
    rows = []
    for path in sorted((output_root / "editions").glob("*/*/*.json")):
        payload = _read_json(path, None)
        if not isinstance(payload, dict) or not payload.get("id"):
            continue
        rows.append({
            "id": payload["id"], "date": payload.get("date"), "slot": payload.get("slot"),
            "status": payload.get("status"), "closedAt": payload.get("closedAt"),
            "path": path.relative_to(output_root).as_posix(),
            "counts": _counts(payload),
        })
    rows.sort(key=lambda row: row["id"], reverse=True)
    return {"generatedAt": now, "editions": rows[:INDEX_LIMIT]}


def _same(left: Any, right: Any, ignore: tuple[str, ...] = ("closedAt", "generatedAt")) -> bool:
    if not isinstance(left, dict) or not isinstance(right, dict):
        return False
    strip = lambda row: {key: value for key, value in row.items() if key not in ignore}
    return strip(left) == strip(right)


def _ensure_site(site_root: Path) -> None:
    if not site_root.exists() or not any(site_root.iterdir()):
        site_root.mkdir(parents=True, exist_ok=True)
        (site_root / ".upsc-generated").write_text(GENERATED_MARKER, encoding="utf-8")


def build_edition(
    output_root: Path,
    date: str,
    slot: str,
    now: str,
    opener: Callable[..., Any],
    transport: Callable[..., Any],
    dry_run: bool = False,
    max_notes: int = 14,
    env: Optional[Mapping[str, str]] = None,
    site_root: Optional[Path] = None,
    feeds_path: Optional[Path] = None,
    base_url: str = BASE_URL,
) -> dict[str, Any]:
    output_root = Path(output_root)
    site_root = Path(site_root) if site_root else ROOT / "upsc-study"
    env = os.environ if env is None else env
    window = slot_window(date, slot)
    this_id = edition_id(date, slot)
    path = _edition_path(output_root, date, slot)
    existing = _read_json(path, None)
    edition = json.loads(json.dumps(existing)) if isinstance(existing, dict) else _empty_edition(date, slot, window)
    edition["window"] = {"from": window[0], "to": window[1]}

    feed_errors: list[dict[str, str]] = []
    discovery = fetch_discovery(
        load_feeds(feeds_path or ROOT / "data/upsc/discovery-feeds.json"), opener,
        window[0], window[1], feed_errors,
    )
    records, _ = _all_current_records(output_root)
    candidates = build_candidates(records.values(), discovery, window)

    am_path = _edition_path(output_root, date, "am")
    am = _read_json(am_path, None) if slot == "pm" else None
    am_changed = False
    pyq_bank = _read_json(PYQ_BANK_PATH, {})
    evidence_failures: dict[str, int] = {}
    held: list[dict[str, Any]] = []
    new_notes: list[tuple[dict[str, Any], dict[str, Any]]] = []
    quick_facts = list(edition.get("quickFacts") or [])
    fact_ids = {row.get("id") for row in quick_facts}
    llm_down = False
    attempted = 0

    def add_fact(candidate: Mapping[str, Any]) -> None:
        fact = _quick_fact(candidate)
        if fact and fact["id"] not in fact_ids:
            fact_ids.add(fact["id"])
            quick_facts.append(fact)

    for candidate in candidates:
        if candidate["band"] == "skip":
            continue
        if any(_matches(candidate, note) for note in (edition.get("notes") or {}).values()):
            continue
        if isinstance(am, dict):
            am_note = next((note for note in (am.get("notes") or {}).values() if _matches(candidate, note)), None)
            if am_note is not None:
                fresh = [row for row in candidate["records"] if row["id"] not in set(am_note.get("recordIds") or [])]
                for row in fresh:
                    am_note.setdefault("updates", []).append({"at": now, "text": str(row.get("title") or ""), "source": _source(row)})
                    am_note.setdefault("recordIds", []).append(row["id"])
                    am_changed = True
                continue
        if candidate["band"] == "useful" or attempted >= max_notes:
            add_fact(candidate)
            continue
        attempted += 1
        topic = {"topic": candidate["title"], "fingerprint": candidate["fingerprint"]}
        try:
            evidence, reason = _gather_evidence(candidate, opener, evidence_failures)
            if not evidence:
                held.append({**topic, "reasons": ["evidence-unavailable", reason or "no-evidence"]})
                continue
            if llm_down:
                held.append({**topic, "reasons": ["llm-unavailable"]})
                continue
            note, reasons = write_note(candidate, evidence, _pyq_options(candidate, pyq_bank), transport, env=env)
        except Exception as error:  # one topic never sinks the edition
            held.append({**topic, "reasons": ["error", str(error)[:200]]})
            continue
        if note is None:
            llm_down = llm_down or reasons == ["llm-unavailable"]
            held.append({**topic, "reasons": reasons})
            continue
        new_notes.append((_complete_note(note, candidate, this_id, date, now), candidate))

    notes = dict(edition.get("notes") or {})
    for note, candidate in new_notes:
        notes[note["id"]] = note
        edition["mains" if _is_mains(note, candidate) else "prelims"].append(note["id"])
        edition["glimpse"].append({"noteId": note["id"], "line": note.get("oneLine", ""), "code": (note.get("codes") or [""])[0]})
    edition["notes"] = notes
    edition["quickFacts"] = quick_facts
    edition["held"] = held
    llm_held = any("llm-unavailable" in row["reasons"] for row in held)
    edition["status"] = "partial" if llm_held or (not notes and held) else "closed"
    edition["closedAt"] = now

    must = [row for row in candidates if row["band"] == "must"]
    report: dict[str, Any] = {
        "editionId": this_id, "dryRun": dry_run, "window": edition["window"],
        "discovery": {"items": len(discovery), "feedErrors": feed_errors},
        "candidates": {band: sum(1 for row in candidates if row["band"] == band) for band in ("must", "useful", "skip")},
        "mustKnow": [{"title": row["title"], "score": row["score"], "kind": row["kind"], "codes": row["codesHint"]} for row in must[:10]],
        "evidenceFailures": evidence_failures,
        "newNotes": len(new_notes), "held": held, "status": edition["status"],
        "written": [], "edition": edition,
    }
    if dry_run:
        return report

    if not _same(existing, edition):
        _write_json(path, edition)
        report["written"].append(path.as_posix())
    if am_changed:
        _write_json(am_path, am)
        report["written"].append(am_path.as_posix())
    pages = [(note, this_id) for note, _ in new_notes]
    if am_changed:
        pages += [(note, am["id"]) for note in am["notes"].values() if note.get("updates")]
    if pages:
        _ensure_site(site_root)
    for note, owner in pages:
        page = site_root / "notes" / _slug(note["slug"], "note") / "index.html"
        _write_text(page, render_note_page(note, owner, base_url))
        report["written"].append(page.as_posix())
    index_path = output_root / "editions" / "index.json"
    index = _build_index(output_root, now)
    if not _same(_read_json(index_path, None), index):
        _write_json(index_path, index)
        report["written"].append(index_path.as_posix())
    return report


def _summary(report: Mapping[str, Any]) -> dict[str, Any]:
    held_reasons: dict[str, int] = {}
    for row in report["held"]:
        key = row["reasons"][0] if row["reasons"] else "unknown"
        held_reasons[key] = held_reasons.get(key, 0) + 1
    edition = report["edition"]
    return {
        "editionId": report["editionId"], "dryRun": report["dryRun"], "status": report["status"],
        "window": report["window"], "discovery": report["discovery"],
        "candidates": report["candidates"], "mustKnow": report["mustKnow"],
        "evidenceFailures": report["evidenceFailures"], "heldByReason": held_reasons,
        "held": report["held"], "newNotes": report["newNotes"],
        "counts": _counts(edition), "written": report["written"],
    }


